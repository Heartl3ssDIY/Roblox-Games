s,out=M.Step(s,15,nil,1,true,false) check(out,"missing body cannot stall active race forever")
s=M.New(0,0,1)
s,out=M.Step(s,15,0/0,1,true,false) check(out,"invalid coordinates do not count as progress")
return tostring(passed).." idle/progress rule checks passed."
