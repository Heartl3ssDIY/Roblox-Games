local passed=0
local function check(ok,label) assert(ok,label) passed+=1 end
local s,out,elapsed=M.New(0,0,1)
s,out=M.Step(s,14.99,0,1,true,false) check(not out,"not early")
s,out=M.Step(s,15,0,1,true,false) check(out,"15 seconds stationary")
s=M.New(0,0,1)
for t=1,120 do s,out=M.Step(s,t,t*28,1,true,false) check(not out,"automatic forward running "..t) end
s=M.New(0,0,1)
for t=1,14 do s,out=M.Step(s,t,t%2==0 and .4 or -.4,1,true,false) check(not out,"small physics jitter") end
s,out=M.Step(s,15,.3,1,true,false) check(out,"jitter cannot keep stalled runner alive")
s=M.New(0,0,1)
s,out=M.Step(s,14,1,1,true,false) check(not out,"new forward progress refreshes timer")
s,out=M.Step(s,28.99,1,1,true,false) check(not out,"refreshed deadline")
s,out=M.Step(s,29,1,1,true,false) check(out,"refreshed timeout")
s=M.New(0,0,1)
s,out=M.Step(s,14,-5,1,true,false)
s,out=M.Step(s,15,0,1,true,false) check(out,"back-and-forth without progress is stuck")
s=M.New(0,0,1)
s,out=M.Step(s,14,0,1,true,true) check(not out,"ability freeze exemption")
s,out=M.Step(s,19,0,1,true,true) check(not out,"freeze duration not counted")
s,out=M.Step(s,19.1,0,1,true,false) check(not out,"release starts fresh window")
